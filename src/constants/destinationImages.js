const DEFAULT_TRAVEL_HERO = 'https://images.unsplash.com/photo-1488646953014-85cb44e25828?auto=format&fit=crop&w=1200&q=80';

// Validador de imagen: filtra imagenes de Wikipedia que no sean fotos reales (como banderas, escudos, svg)
function isValidWikipediaPhoto(url) {
  if (!url || typeof url !== 'string' || !url.startsWith('http')) return false;
  const lower = url.toLowerCase();
  if (lower.includes('.svg') || lower.includes('flag') || lower.includes('bandera') || lower.includes('escudo') || lower.includes('coat_of_arms')) {
    return false;
  }
  return true;
}

export function normalizeCityKey(city) {
  if (!city) return '';
  const cleaned = city
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
  return ALIAS_MAP[cleaned] || cleaned;
}

export function getDestinationImageUrl(cityName, wikiThumbnailUrl, wikiOriginalUrl) {
  const key = normalizeCityKey(cityName);

  // 1. Prioridad: Fotografia profesional curada de alta definicion (Cero problemas de CORS o bloqueo)
  if (key && DESTINATION_GALLERY[key]) {
    return DESTINATION_GALLERY[key].hero;
  }

  // 2. Si no esta en el catalogo curado, usar foto de alta resolucion de Wikipedia si es fotografia legitima
  if (isValidWikipediaPhoto(wikiOriginalUrl)) {
    return wikiOriginalUrl;
  }

  // 3. Miniatura de Wikipedia si es fotografia legitima
  if (isValidWikipediaPhoto(wikiThumbnailUrl)) {
    return wikiThumbnailUrl;
  }

  // 4. Imagen de respaldo de viaje garantizada
  return DEFAULT_TRAVEL_HERO;
}

